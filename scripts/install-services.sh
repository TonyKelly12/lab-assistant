#!/usr/bin/env bash
# Install + enable the lab-assistant services for one node, so a power-on brings
# everything up on its own. Run once per node (re-run after a git pull to pick
# up unit changes). Daily after this: just turn the Pi on.
#
#   sudo bash scripts/install-services.sh <orin|shop|homelab> [--voice] [--console]
#
#   orin      broker + router + case OLED        (+ voice-service with --voice)
#   shop      camera + projector + bench-vision   (+ voice-satellite with --voice)
#   homelab   the brain bridge
#   --voice   also install the voice service/satellite for that node
#   --console install the web console (lab-dashboard) + a narrow sudoers rule
#
# It rewrites User= and WorkingDirectory= in each unit to this account and clone
# path, so you don't edit them by hand. Secrets are never written here: it only
# creates empty /etc/default/<unit> stubs for you to drop MQTT_PASS etc. into.
set -euo pipefail

ROLE="${1:-}"; shift || true
VOICE=0; CONSOLE=0
for a in "$@"; do case "$a" in
  --voice) VOICE=1;; --console) CONSOLE=1;;
  *) echo "unknown option: $a"; exit 1;;
esac; done

if [ -z "$ROLE" ]; then
  echo "usage: sudo bash scripts/install-services.sh <orin|shop|homelab> [--voice] [--console]"; exit 1
fi
if [ "$(id -u)" != "0" ]; then
  echo "run with sudo (it writes to /etc/systemd/system): sudo bash $0 $ROLE $*"; exit 1
fi

REPO="$(cd "$(dirname "$0")/.." && pwd)"
RUN_USER="${SUDO_USER:-root}"
echo ">> repo: $REPO"
echo ">> service user: $RUN_USER"

# units per role
case "$ROLE" in
  orin)    units=(lab-router oled-stats); [ $VOICE -eq 1 ] && units+=(voice-service);;
  shop)    units=(camera-node render-node shopvision); [ $VOICE -eq 1 ] && units+=(voice-satellite);;
  homelab) units=(brain-bridge);;
  *) echo "unknown role: $ROLE (use orin|shop|homelab)"; exit 1;;
esac
[ $CONSOLE -eq 1 ] && units+=(lab-dashboard)

install_unit() {
  local u="$1" src="$REPO/systemd/$1.service"
  [ -f "$src" ] || { echo "   ! missing unit file: $src"; return 1; }
  sed -e "s|^User=.*|User=$RUN_USER|" \
      -e "s|^WorkingDirectory=.*|WorkingDirectory=$REPO|" \
      "$src" > "/etc/systemd/system/$1.service"
  echo "   installed $1.service"
}

echo ">> installing units: ${units[*]}"
for u in "${units[@]}"; do install_unit "$u"; done

# env stubs (so you have a place for MQTT_PASS / DASHBOARD_KEY; never populated here)
for f in lab-router shopvision render-node voice-service voice-satellite brain-bridge lab-dashboard; do
  if printf '%s\n' "${units[@]}" | grep -qx "$f" && [ ! -f "/etc/default/$f" ]; then
    printf '# Set secrets here, e.g.\n# MQTT_PASS=change-me\n' > "/etc/default/$f"
    [ "$f" = "lab-dashboard" ] && printf '# DASHBOARD_KEY=change-me\n' >> "/etc/default/$f"
    echo "   created /etc/default/$f (add secrets)"
  fi
done

systemctl daemon-reload
echo ">> enabling (start now + on boot): ${units[*]}"
systemctl enable --now "${units[@]}"

# system deps on the Orin, only if their units exist
if [ "$ROLE" = "orin" ]; then
  for dep in mosquitto ollama; do
    if systemctl list-unit-files | grep -q "^$dep.service"; then
      systemctl enable --now "$dep" && echo "   enabled $dep"
    else
      echo "   note: $dep.service not found — install it so the broker/models start on boot"
    fi
  done
fi

# console: generate a tight sudoers rule for exactly this node's controllable units
if [ $CONSOLE -eq 1 ]; then
  ctrl=("${units[@]}")
  [ "$ROLE" = "orin" ] && ctrl+=(mosquitto ollama)
  tmp="$(mktemp)"
  {
    echo "# generated by install-services.sh — lab console control, least privilege"
    printf 'Cmnd_Alias LAB_SVC = '
    first=1
    for u in "${ctrl[@]}"; do
      for act in start stop restart; do
        [ $first -eq 1 ] || printf ', '
        printf '/usr/bin/systemctl %s %s' "$act" "$u"
        first=0
      done
    done
    printf '\n%s ALL=(root) NOPASSWD: LAB_SVC\n' "$RUN_USER"
  } > "$tmp"
  if visudo -c -f "$tmp" >/dev/null 2>&1; then
    install -m 0440 "$tmp" /etc/sudoers.d/lab-assistant
    echo "   installed /etc/sudoers.d/lab-assistant (control limited to: ${ctrl[*]})"
  else
    echo "   ! generated sudoers failed validation; left at $tmp — review and install by hand"
  fi
  rm -f "$tmp" 2>/dev/null || true
fi

echo
echo ">> done. Status now:"
systemctl --no-pager --plain is-active "${units[@]}" 2>/dev/null | paste -d' ' <(printf '%s\n' "${units[@]}") - || true
echo
echo "Next: put secrets in /etc/default/<unit> (MQTT_PASS, and DASHBOARD_KEY for the console),"
echo "then: sudo systemctl restart ${units[*]}"
[ $CONSOLE -eq 1 ] && echo "Console: http://$(hostname -I 2>/dev/null | awk '{print $1}'):8099"
